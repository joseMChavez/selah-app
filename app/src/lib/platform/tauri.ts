// Único archivo de la interfaz que importa APIs de Tauri. Migrar a Electron = reescribir este archivo.
// Cada funcionalidad del backend es un plugin interno: sus comandos se llaman «plugin:<funcionalidad>|<comando>».
import { convertFileSrc, invoke } from "@tauri-apps/api/core";
import { listen } from "@tauri-apps/api/event";
import type { OfficeProgress, OutputState, Platform, StoredSettings } from "./types";

export const tauriPlatform: Platform = {
  listMonitors: () => invoke("plugin:output|list_monitors"),
  openOutput: (monitorIndex) => invoke("plugin:output|open_output", { monitorIndex }),
  closeOutput: () => invoke("plugin:output|close_output"),
  setOutputContent: (content) => invoke("plugin:output|set_output_content", { content }),
  getOutputState: () => invoke("plugin:output|get_output_state"),
  setOutputStyle: (style) => invoke("plugin:output|set_output_style", { style }),
  onOutputState: (handler) => listen<OutputState>("output-state", (event) => handler(event.payload)),
  pickMedia: (title, filterName) => invoke("plugin:media|pick_media", { title, filterName }),
  pickMediaFolder: (title) => invoke("plugin:media|pick_media_folder", { title }),
  pickBackground: (title, filterName) => invoke("plugin:media|pick_background", { title, filterName }),
  allowBackgrounds: (paths) => invoke("plugin:media|allow_backgrounds", { paths }),
  convertPresentation: (path) => invoke("plugin:presentations|convert_presentation", { path }),
  officeAvailable: () => invoke("plugin:presentations|office_available"),
  officeStatus: () => invoke("plugin:presentations|office_status"),
  officeInstall: () => invoke("plugin:presentations|office_install"),
  officeCancel: () => invoke("plugin:presentations|office_cancel"),
  officeRemove: () => invoke("plugin:presentations|office_remove"),
  onOfficeProgress: (handler) => listen<OfficeProgress>("office-progress", (event) => handler(event.payload)),
  mediaUrl: (path) => convertFileSrc(path),
  reportOutputError: (message) => invoke("plugin:output|report_output_error", { message }),
  logError: (message) => invoke("log_client_error", { message }),
  onOutputError: (handler) => listen<string>("output-error", (event) => handler(event.payload)),
  outputNavigate: (forward) => invoke("plugin:output|output_navigate", { forward }),
  onOutputNavigate: (handler) => listen<boolean>("output-navigate", (event) => handler(event.payload)),
  listBibles: () => invoke("plugin:bible|list_bibles"),
  importBibles: (title, filterName) => invoke("plugin:bible|import_bibles", { title, filterName }),
  removeBible: (id) => invoke("plugin:bible|remove_bible", { id }),
  getChapter: (bibleId, book, chapter) => invoke("plugin:bible|get_chapter", { bibleId, book, chapter }),
  searchBible: (bibleId, query) => invoke("plugin:bible|search_bible", { bibleId, query }),
  settingsGet: () => invoke("plugin:settings|settings_get"),
  settingsSet: (key, value) => invoke("plugin:settings|settings_set", { key, value }),
  settingsReset: (keys) => invoke("plugin:settings|settings_reset", { keys }),
  onSettingsChanged: (handler) => listen<StoredSettings>("settings-changed", (event) => handler(event.payload)),
  storePath: () => invoke("plugin:settings|store_path"),
  songsList: () => invoke("plugin:songs|songs_list"),
  songSave: (song) => invoke("plugin:songs|song_save", { song }),
  songDelete: (id) => invoke("plugin:songs|song_delete", { id }),
  setlistGet: () => invoke("plugin:songs|setlist_get"),
  setlistSet: (ids) => invoke("plugin:songs|setlist_set", { ids }),
  songsReset: () => invoke("plugin:songs|songs_reset"),
  obsDetect: () => invoke("plugin:obs|obs_detect"),
  obsEnableWebsocket: () => invoke("plugin:obs|obs_enable_websocket"),
  obsLaunch: () => invoke("plugin:obs|obs_launch"),
  obsConnect: () => invoke("plugin:obs|obs_connect"),
  obsDisconnect: () => invoke("plugin:obs|obs_disconnect"),
  obsStatus: () => invoke("plugin:obs|obs_status"),
  obsSetup: (waitText) => invoke("plugin:obs|obs_setup", { waitText }),
  obsSetScene: (scene) => invoke("plugin:obs|obs_set_scene", { scene }),
  obsShowText: (source, text, credit) => invoke("plugin:obs|obs_show_text", { source, text, credit }),
  obsHideText: (source) => invoke("plugin:obs|obs_hide_text", { source }),
  obsCameras: () => invoke("plugin:obs|obs_cameras"),
  obsSetCamera: (device) => invoke("plugin:obs|obs_set_camera", { device }),
  obsPreview: () => invoke("plugin:obs|obs_preview"),
  obsSetDestination: (server, key) => invoke("plugin:obs|obs_set_destination", { server, key }),
  obsStartStream: () => invoke("plugin:obs|obs_start_stream"),
  obsStopStream: () => invoke("plugin:obs|obs_stop_stream"),
};
